  function todayPlan(dateStr) {
    // 以 2024-01-01 为基准的天数做索引，保证每天不同且连续
    const base = new Date(2024, 0, 1);
    const [y, m, d] = dateStr.split('-').map(Number);
    const cur = new Date(y, m - 1, d);
    const idx = Math.max(0, Math.round((cur - base) / 86400000));
    return {
      workout: WORKOUTS[idx % WORKOUTS.length],
      stretch: STRETCHES[idx % STRETCHES.length],
      rotation: idx
    };
  }

