  /* ---------- 热量计算 ---------- */
  // Mifflin-St Jeor 女性公式：BMR = 10*kg + 6.25*cm - 5*age - 161
  function bmr(body) {
    const kg = Number(body && body.weight) || 0;
    const cm = Number(body && body.height) || 0;
    const age = Number(body && body.age) || 30;
    if (!kg || !cm) return 0;
    return Math.round(10 * kg + 6.25 * cm - 5 * age - 161);
  }
  // 运动消耗（粗略 MET 估算）：抗阻约 5 kcal/min，有氧约 6 kcal/min
  function burn(day) {
    const res = Number(day && day.resistance && day.resistance.min) || 0;
    const aer = Number(day && day.aerobic && day.aerobic.min) || 0;
    return Math.round(res * 5 + aer * 6);
  }
